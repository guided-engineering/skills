// Generate (or with --check, verify) the requirement map of this repository's
// plan: .guides/traceability/skills-repository.requirements.md. The map is
// derived from the prompt by the validator bundled in the Skills; edit the
// prompt, never the map. No dependencies.
//
//   node tools/trace.mjs            write the map
//   node tools/trace.mjs --check    exit 1 when the committed map is out of date
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prompt = '.guides/prompts/prompt.skills-repository.yaml';
const out = join(root, '.guides', 'traceability', 'skills-repository.requirements.md');
const validator = join(root, 'skills', 'ops-author', 'scripts', 'ops-validate.mjs');

const run = spawnSync(process.execPath, [validator, '--trace', prompt], { cwd: root, encoding: 'utf8' });
if (run.status !== 0) {
  process.stderr.write(run.stdout + run.stderr);
  process.exit(1);
}
const text = `# Requirement map of the Skills repository plan

Generated by \`npm run trace\` from [\`${prompt}\`](../prompts/prompt.skills-repository.yaml)
with the validator bundled in the Skills. Do not edit: change the prompt and
regenerate. \`npm run trace -- --check\` fails when this file is out of date.

The requirements come from sections 5 and 8 of the request kept in
OpenPrompt-Specification (\`.guides/product/refoundation-request.md\`). A
generated map shows that every requirement has a step and a check. Whether the
translation lost anything was checked by reading, in
\`.guides/traceability/refoundation.coverage-audit.md\` of that repository. What
each check showed is in the run record under \`.guides/operation/worklog/\`.

${run.stdout.trimEnd()}
`;

if (process.argv.includes('--check')) {
  let committed = '';
  try {
    committed = readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    // reported below
  }
  if (committed !== text) {
    console.error('The requirement map is out of date. Run `npm run trace` and commit the result.');
    process.exit(1);
  }
  console.log('requirement map is up to date');
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
